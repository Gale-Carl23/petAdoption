CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'ADOPTER',
    CONSTRAINT uq_app_users_email UNIQUE (email)
);

CREATE TABLE pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    breed VARCHAR(100) NOT NULL,
    age INTEGER NOT NULL,
    description VARCHAR(1000),
    image_url VARCHAR(500),
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE'
);

CREATE TABLE adoption_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applicant_user_id BIGINT NOT NULL,
    pet_id BIGINT NOT NULL,
    reason_for_adoption VARCHAR(1000) NOT NULL,
    housing_type VARCHAR(100) NOT NULL,
    pet_experience VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    submitted_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_adoption_applicant FOREIGN KEY (applicant_user_id)
        REFERENCES app_users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_adoption_pet FOREIGN KEY (pet_id)
        REFERENCES pets (id) ON DELETE RESTRICT
);

CREATE TABLE donations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_user_id BIGINT NOT NULL,
    full_name VARCHAR(100),
    amount NUMERIC(12, 2) NOT NULL,
    date_sent DATE NOT NULL,
    proof_file_path VARCHAR(500) NOT NULL,
    message VARCHAR(1000),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING_VERIFICATION',
    submitted_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_donation_donor FOREIGN KEY (donor_user_id)
        REFERENCES app_users (id) ON DELETE RESTRICT
);

CREATE TABLE referral_survey_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    respondent_user_id BIGINT NOT NULL,
    application_id BIGINT UNIQUE,
    donation_id BIGINT UNIQUE,
    referral_source VARCHAR(40) NOT NULL,
    submitted_at TIMESTAMP NOT NULL,
    CONSTRAINT ck_referral_survey_submission CHECK (
        (application_id IS NOT NULL AND donation_id IS NULL)
        OR (application_id IS NULL AND donation_id IS NOT NULL)
    ),
    CONSTRAINT fk_referral_respondent FOREIGN KEY (respondent_user_id)
        REFERENCES app_users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_referral_application FOREIGN KEY (application_id)
        REFERENCES adoption_applications (id) ON DELETE CASCADE,
    CONSTRAINT fk_referral_donation FOREIGN KEY (donation_id)
        REFERENCES donations (id) ON DELETE CASCADE
);

CREATE INDEX ix_pets_status ON pets (status);
CREATE INDEX ix_adoption_applicant_submitted
    ON adoption_applications (applicant_user_id, submitted_at DESC);
CREATE INDEX ix_adoption_pet_submitted
    ON adoption_applications (pet_id, submitted_at DESC);
CREATE INDEX ix_adoption_status_submitted
    ON adoption_applications (status, submitted_at DESC);
CREATE INDEX ix_donations_donor_submitted
    ON donations (donor_user_id, submitted_at DESC);
CREATE INDEX ix_donations_status_submitted
    ON donations (status, submitted_at DESC);
CREATE INDEX ix_referral_source_submitted
    ON referral_survey_responses (referral_source, submitted_at DESC);
